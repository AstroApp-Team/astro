import { zValidator } from "@hono/zod-validator";
import { createGateway, createUIMessageStream, createUIMessageStreamResponse } from "ai";
import { Hono } from "hono";
import { cors } from "hono/cors";

import {
  PASSWORD_QUERY_PARAM,
  REALTIME_TOKEN_TTL_SECONDS,
  REALTIME_TOOLS,
  VOICE_MODEL_ID,
} from "../shared/realtime.ts";
import {
  AuthQuerySchema,
  CreateProjectSchema,
  PasswordSchema,
  ProjectIdParamSchema,
  RealtimeSetupSchema,
  SaveProjectFileSchema,
  UpdateProjectStateSchema,
  ViewRequestSchema,
} from "../shared/schemas.ts";
import { viewSpec, viewTitle, type ViewUIMessage } from "../shared/view.ts";
import { createDb } from "./db/client.ts";
import { D1ProjectRepository } from "./repositories/d1-project-repository.ts";
import type { ProjectRepository } from "./repositories/project-repository.ts";
import { buildView, rebuildModel, viewModel } from "./view-agent.ts";

/**
 * `CloudflareBindings` (not `Env`) is generated by
 * `wrangler types --env-interface CloudflareBindings`. The explicit name avoids
 * colliding with Hono's own `Env` type.
 */
type AppEnv = { Bindings: CloudflareBindings };

/**
 * Origins the Capacitor WebView uses once the app is bundled natively.
 * iOS serves from capacitor://localhost, Android from https://localhost.
 */
const NATIVE_ORIGINS = ["capacitor://localhost", "http://localhost", "https://localhost"];

/**
 * Constant-time string compare so a shared password cannot be recovered a
 * character at a time. `crypto.subtle.timingSafeEqual` is Workers-only and
 * would not run in the node test project, so this stays portable.
 */
function passwordMatches(candidate: string, expected: string): boolean {
  if (expected.length === 0 || candidate.length !== expected.length) return false;

  let difference = 0;
  for (let index = 0; index < candidate.length; index += 1) {
    difference |= candidate.charCodeAt(index) ^ expected.charCodeAt(index);
  }
  return difference === 0;
}

function projectRepository(db: D1Database): ProjectRepository {
  return new D1ProjectRepository(createDb(db));
}

/**
 * Routes MUST stay chained. Breaking the chain into separate `api.get(...)`
 * statements silently destroys RPC type inference — the client still compiles,
 * it just degrades to `any`.
 */
const api = new Hono<AppEnv>()
  .get("/health", (c) => c.json({ ok: true } as const))

  /** Lets the UI check the password before it opens a billable session. */
  .post("/auth", zValidator("json", PasswordSchema), (c) => {
    const { password } = c.req.valid("json");
    if (!passwordMatches(password, c.env.APP_PASSWORD)) {
      return c.json({ error: "Wrong password" }, 401);
    }
    return c.json({ ok: true } as const);
  })

  /**
   * Mints a short-lived AI Gateway client secret. The browser never sees the
   * Gateway key; it gets a `vcst_` token that expires in a minute.
   *
   * The password rides in the query string because `experimental_useRealtime`
   * owns this fetch and sends no custom headers.
   */
  .post("/realtime/setup", async (c) => {
    if (!passwordMatches(c.req.query(PASSWORD_QUERY_PARAM) ?? "", c.env.APP_PASSWORD)) {
      return c.json({ error: "Wrong password" }, 401);
    }

    const apiKey = c.env.AI_GATEWAY_API_KEY;
    if (!apiKey) {
      return c.json({ error: "AI_GATEWAY_API_KEY is not configured on this Worker" }, 500);
    }

    const gateway = createGateway({ apiKey });

    try {
      const token = await gateway.experimental_realtime.getToken({
        model: VOICE_MODEL_ID,
        expiresAfterSeconds: REALTIME_TOKEN_TTL_SECONDS,
      });

      const setup = RealtimeSetupSchema.safeParse(token);
      if (!setup.success) {
        return c.json({ error: "The Gateway returned an unusable realtime token" }, 502);
      }

      /**
       * `tools` is ours, not the Gateway's — `getToken()` only mints a secret.
       * The hook reads the tool list off this response and puts it in the
       * `session-update` it sends when the socket opens, so a tool declared
       * anywhere else in the app would never reach the model.
       */
      return c.json({ ...setup.data, tools: REALTIME_TOOLS });
    } catch (error) {
      return c.json(
        { error: error instanceof Error ? error.message : "Realtime setup failed" },
        502,
      );
    }
  })

  /**
   * Runs the coding agent and streams it back as a UI message stream.
   *
   * It streams because the caller is a voice conversation: the browser answers
   * the model's tool call immediately and then has ten or twenty seconds to
   * account for, and a silent request is indistinguishable from a dead one.
   * `data-progress` is transient — status, not history — and so is
   * `data-draft`, the page as it is being written, which the client paints
   * immediately. `data-view` is the finished document. `data-cost` is
   * transient too: the client banks it.
   */
  .post("/view", zValidator("json", ViewRequestSchema), (c) => {
    const { password, request, currentHtml, mode, pageErrors } = c.req.valid("json");

    if (!passwordMatches(password, c.env.APP_PASSWORD)) {
      return c.json({ error: "Wrong password" }, 401);
    }

    const apiKey = c.env.AI_GATEWAY_API_KEY;
    if (!apiKey) {
      return c.json({ error: "AI_GATEWAY_API_KEY is not configured on this Worker" }, 500);
    }

    const stream = createUIMessageStream<ViewUIMessage>({
      execute: async ({ writer }) => {
        const view = await buildView({
          model: mode === "rebuild" ? rebuildModel(apiKey) : viewModel(apiKey),
          mode,
          request,
          currentHtml,
          pageErrors,
          onProgress: (progress) =>
            writer.write({ type: "data-progress", data: progress, transient: true }),
          /**
           * A rebuild keeps its drafts to itself: the old page stays usable for
           * the ten-plus seconds the rewrite takes, instead of being replaced by a
           * half-written one the user cannot use.
           */
          onDraft: (html) => {
            if (mode !== "rebuild") {
              writer.write({ type: "data-draft", data: { html }, transient: true });
            }
          },
          onCost: (usd) => writer.write({ type: "data-cost", data: { usd }, transient: true }),
        });

        writer.write({ type: "data-view", data: view });
      },
      /**
       * Returned to the browser as an error part instead of a dropped
       * connection — by the time the agent can fail, the response has already
       * begun, so a status code is no longer available.
       */
      onError: (error) => (error instanceof Error ? error.message : "The coding agent failed."),
    });

    return createUIMessageStreamResponse({ stream });
  })

  /** Lists saved projects ordered by most recently updated. */
  .get("/projects", zValidator("query", AuthQuerySchema), async (c) => {
    const query = c.req.valid("query");
    if (!passwordMatches(query[PASSWORD_QUERY_PARAM] ?? "", c.env.APP_PASSWORD)) {
      return c.json({ error: "Wrong password" }, 401);
    }

    const projects = await projectRepository(c.env.DB).listAll();
    return c.json({ projects });
  })

  /** Creates a new project with its initial `index.html` and optional state. */
  .post("/projects", zValidator("json", CreateProjectSchema), async (c) => {
    const { password, title, spec, html, stateData } = c.req.valid("json");
    if (!passwordMatches(password, c.env.APP_PASSWORD)) {
      return c.json({ error: "Wrong password" }, 401);
    }

    const resolvedTitle = title.trim() || viewTitle(html);
    const resolvedSpec = spec || (viewSpec(html) ?? []).join("\n");

    const project = await projectRepository(c.env.DB).create({
      title: resolvedTitle,
      spec: resolvedSpec,
      initialFile: { filePath: "index.html", content: html },
      ...(stateData !== undefined && { initialStateData: stateData }),
    });

    return c.json({ project }, 201);
  })

  /** Fetches a single project along with its files and latest serialized state. */
  .get(
    "/projects/:id",
    zValidator("param", ProjectIdParamSchema),
    zValidator("query", AuthQuerySchema),
    async (c) => {
      const query = c.req.valid("query");
      if (!passwordMatches(query[PASSWORD_QUERY_PARAM] ?? "", c.env.APP_PASSWORD)) {
        return c.json({ error: "Wrong password" }, 401);
      }

      const { id } = c.req.valid("param");
      const project = await projectRepository(c.env.DB).getById(id);
      if (!project) {
        return c.json({ error: "Project not found" }, 404);
      }

      return c.json({ project });
    },
  )

  /** Upserts a source file (`index.html`, etc.) and updates project metadata. */
  .put(
    "/projects/:id/files",
    zValidator("param", ProjectIdParamSchema),
    zValidator("json", SaveProjectFileSchema),
    async (c) => {
      const { id } = c.req.valid("param");
      const { password, filePath, content, title, spec } = c.req.valid("json");
      if (!passwordMatches(password, c.env.APP_PASSWORD)) {
        return c.json({ error: "Wrong password" }, 401);
      }

      const file = await projectRepository(c.env.DB).saveFile({
        projectId: id,
        filePath,
        content,
        ...(title !== undefined || spec !== undefined
          ? {
              projectMeta: {
                ...(title !== undefined && { title }),
                ...(spec !== undefined && { spec }),
              },
            }
          : {}),
      });

      if (!file) {
        return c.json({ error: "Project not found" }, 404);
      }

      return c.json({ file });
    },
  )

  /** Upserts the serialized JSON state of a project. */
  .put(
    "/projects/:id/state",
    zValidator("param", ProjectIdParamSchema),
    zValidator("json", UpdateProjectStateSchema),
    async (c) => {
      const { id } = c.req.valid("param");
      const { password, stateData } = c.req.valid("json");
      if (!passwordMatches(password, c.env.APP_PASSWORD)) {
        return c.json({ error: "Wrong password" }, 401);
      }

      const state = await projectRepository(c.env.DB).updateState(id, stateData);
      if (!state) {
        return c.json({ error: "Project not found" }, 404);
      }

      return c.json({ state });
    },
  )

  /** Deletes a project and cascades removal to its files and state. */
  .delete(
    "/projects/:id",
    zValidator("param", ProjectIdParamSchema),
    zValidator("query", AuthQuerySchema),
    async (c) => {
      const query = c.req.valid("query");
      if (!passwordMatches(query[PASSWORD_QUERY_PARAM] ?? "", c.env.APP_PASSWORD)) {
        return c.json({ error: "Wrong password" }, 401);
      }

      const { id } = c.req.valid("param");
      const deleted = await projectRepository(c.env.DB).delete(id);
      if (!deleted) {
        return c.json({ error: "Project not found" }, 404);
      }

      return c.json({ ok: true } as const);
    },
  );

const app = new Hono<AppEnv>().use("/api/*", cors({ origin: NATIVE_ORIGINS })).route("/api", api);

export type AppType = typeof app;

export default app;
