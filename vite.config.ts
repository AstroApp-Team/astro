import { cloudflare } from "@cloudflare/vite-plugin";
import { cloudflareTest, readD1Migrations } from "@cloudflare/vitest-plugin";
import react from "@vitejs/plugin-react";
import { fileURLToPath } from "node:url";
import { defineConfig, lazyPlugins } from "vite-plus";

import { studioSavePlugin } from "./scripts/studio-save-plugin.ts";

/**
 * The Cloudflare plugin must not load under Vitest.
 *
 * vite-plus injects `resolve.external` (every Node builtin) into all
 * environments, and @cloudflare/vite-plugin hard-rejects that on Worker
 * environments — so `vp test` dies at config resolution. It is also redundant
 * there: the "workers" project below gets its workerd runtime from
 * cloudflareTest() instead. Dev and build are unaffected.
 */
const isVitest = process.env["VITEST"] !== undefined;

/**
 * Clean-architecture aliases, mirroring `compilerOptions.paths` in
 * tsconfig.app.json. Regex `find` rather than the string form: rollup's alias
 * only rewrites a string key on an exact match or when followed by `/`, and the
 * regex makes both cases explicit.
 */
const layer = (dir: string) => fileURLToPath(new URL(`./${dir}/`, import.meta.url));

const aliases = [
  { find: /^@core\//, replacement: layer("src/core") },
  { find: /^@infra\//, replacement: layer("src/infrastructure") },
  { find: /^@presentation\//, replacement: layer("src/presentation") },
  { find: /^@shared\//, replacement: layer("shared") },
];

export default defineConfig({
  // lazyPlugins keeps these from being constructed when vp only loads this file
  // to read the lint/fmt/test metadata blocks below.
  plugins: lazyPlugins(() => [
    // Native Oxc React Compiler (oxc-transform-react). Vite marks this
    // experimental; the stable fallback is:
    //   react(), babel({ presets: [reactCompilerPreset()] })
    // via @rolldown/plugin-babel + babel-plugin-react-compiler.
    react({ compiler: true }),
    // The Studio's Save button writes its two files through this middleware. It is
    // `apply: "serve"`, so `vp build` never sees it and a shipped bundle has no
    // endpoint to call — see scripts/studio-save-plugin.ts.
    studioSavePlugin(),
    ...(isVitest ? [] : [cloudflare()]),
  ]),

  resolve: { alias: aliases },

  /**
   * Reachable from the network, because the phone is a supported client and so is a
   * Tailscale hostname.
   *
   * `host: true` binds every interface, so `vp dev` is reachable from a phone on the
   * same tailnet or Wi-Fi without a `--host` flag. `allowedHosts` is Vite's own host
   * check, which exists to stop DNS rebinding: it accepts `localhost`, `*.localhost`
   * and every IP address by default — so a Tailscale IP (`100.x.y.z`) already works
   * and a MagicDNS name (`box.tailnet.ts.net`) does not. `.ts.net` is the narrow
   * answer: MagicDNS names only, not "any hostname on the internet".
   *
   * The Studio's save endpoints sit behind this same server. They do not check
   * `Host` — over a tailnet that check answers the wrong question — they require the
   * `x-astro-studio-save` header, which a cross-origin page cannot attach without a
   * CORS preflight this server does not answer. See `scripts/studio-save-plugin.ts`.
   */
  server: {
    host: true,
    allowedHosts: [".ts.net"],
  },

  /**
   * `@theatre/studio` is CJS and reaches the app only through a dynamic import
   * inside an `import.meta.env.DEV` guard (see infrastructure/theatre/studioInit.ts).
   * Naming it here pre-bundles it at server start; left out, the first import
   * triggers a re-optimize and a full page reload mid-session.
   *
   * It is *not* in `optimizeDeps.exclude`: the 0.7 bundle is a self-contained CJS
   * file with no `?raw` style imports, so it needs the optimizer, not an escape
   * from it.
   */
  optimizeDeps: { include: ["@theatre/studio"] },

  staged: {
    "*": "vp check --fix",
  },
  fmt: {
    ignorePatterns: [
      ".agents/**",
      ".claude/**",
      "dist/**",
      // Generated by `wrangler types` and `drizzle-kit generate` — reformatting
      // them just creates churn on every regeneration.
      "worker-configuration.d.ts",
      "drizzle/**",
      // Written by the Studio's Save button (`scripts/studio-save-plugin.ts`),
      // which serialises with `JSON.stringify(…, 2)`. The formatter collapses
      // short arrays onto one line, so every Save would leave the tree "dirty to
      // fmt" and a `vp check --fix` would fight the plugin's output forever.
      "src/infrastructure/theatre/states/astro.local.state.json",
      "src/infrastructure/theatre/states/astro.local.shapes.json",
      // Written by `scripts/theatre-state.mjs`, which serialises the same way, so
      // every `pnpm run theatre:state -- import` expands every `handles` array.
      // Same fight, same reason.
      "src/infrastructure/theatre/states/portfolio-project.state.json",
      // Written by the machine editor's Save (`/__astro-editor/save`), which
      // serialises with `JSON.stringify(…, 2)` too. The workspace file is
      // git-ignored, but the formatter still sees it on disk.
      "src/infrastructure/theatre/animationStateMachine/definitions/*.json",
    ],
  },
  lint: {
    ignorePatterns: [
      ".agents/**",
      ".claude/**",
      "dist/**",
      "worker-configuration.d.ts",
      "drizzle/**",
    ],
    plugins: ["react", "react-perf", "jsx-a11y", "promise", "import"],
    jsPlugins: [{ name: "vite-plus", specifier: "vite-plus/oxlint-plugin" }],
    rules: { "vite-plus/prefer-vite-plus-imports": "error" },
    options: { typeAware: true, typeCheck: true },
  },

  test: {
    projects: [
      {
        resolve: { alias: aliases },
        // Pure logic: Zod schemas and Hono routes exercised via app.request().
        // No Workers runtime needed, so these stay fast.
        test: {
          name: "node",
          environment: "node",
          include: ["src/**/*.test.ts", "worker/**/*.test.ts", "shared/**/*.test.ts"],
          // *.workers.test.ts belongs to the workers project below; without this
          // the node project also matches it and fails on `cloudflare:test`.
          exclude: ["**/*.workers.test.ts"],
        },
      },
      {
        resolve: { alias: aliases },
        // Anything touching a real binding (D1) runs inside workerd.
        plugins: [
          cloudflareTest(async () => ({
            wrangler: { configPath: "./wrangler.jsonc" },
            miniflare: {
              // Handed to the setup file, which applies them before each suite
              // so every test file starts from a migrated, empty database.
              bindings: {
                TEST_MIGRATIONS: await readD1Migrations("./drizzle/migrations"),
              },
            },
          })),
        ],
        test: {
          name: "workers",
          include: ["worker/**/*.workers.test.ts"],
          setupFiles: ["./worker/test/apply-migrations.ts"],
        },
      },
    ],
  },
});
